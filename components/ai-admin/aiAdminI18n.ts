export function aiAdminT(language: UiLanguage, section: keyof typeof aiAdminDict.fi, key: string) {
  const dict = aiAdminDict[language] || aiAdminDict.fi;
  const sectionDict = dict[section] as Record<string, string>;
  const fallbackSectionDict = aiAdminDict.fi[section] as Record<string, string>;
  return sectionDict[key] || fallbackSectionDict[key] || key;
}
